// ─── Aides de construction ───────────────────────────────────────────────────

/** Ligne d'ingrédient. */
function i(
  ingredientId: string,
  quantity: number,
  unit: Unit,
  extra: { optional?: boolean; note?: string } = {},
): RecipeIngredient {
  return { ingredientId, quantity, unit, ...extra };
}

/** Étape, avec minuteur facultatif (minutes). */
function s(text: string, timerMin?: number): RecipeStep {
  return timerMin === undefined ? { text } : { text, timerMin };
}

